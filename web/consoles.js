// RetroArch com um core específico.
const RA = (core, label) => ({
  key: `ra-${core}`, name: `RetroArch · ${label || core}`, exe: ['retroarch.exe'],
  args: `-L "cores\\${core}_libretro.dll" "{rom}"`, url: 'https://www.retroarch.com/', core,
});

const C = (id, name, maker, year, ext, emus) => ({
  id, name, maker, year, ext: ext.split(' '),
  emus: emus.map((e) => (typeof e === 'string' ? { key: e, ...EMUS[e] } : e)),
});

